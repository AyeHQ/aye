/// Which reading of `[...]` sets a copy had, and so which of a pin's
/// answers it gave.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FnmatchAnswers {
    /// The unittest adapter's copy, which read sets as
    /// `fnmatch._translate` does: CPython 3.13's `fnmatch.fnmatchcase`
    /// gives the same answers.
    CPython,
    /// The pytest adapter's copy and the doctest adapter's, which gave the
    /// same answers: they differ from CPython's for a set whose first item
    /// is a reversed range followed by `!` (`[&-%!a]`).
    Legacy,
}

