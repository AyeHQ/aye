/// Asserts that `fnmatch(name, pattern)` gives the pinned `answers` for
/// every pattern and name, listing each pair that doesn't.
pub fn assert_fnmatch_pins(answers: FnmatchAnswers, fnmatch: impl Fn(&str, &str) -> bool) {
    let mut wrong = Vec::new();
    for (pattern, cpython, legacy) in FNMATCH_PINS {
        let pinned = match answers {
            FnmatchAnswers::CPython => cpython,
            FnmatchAnswers::Legacy => legacy,
        };
        for (name, pinned) in FNMATCH_NAMES.iter().zip(pinned.chars()) {
            let matched = fnmatch(name, pattern);
            if matched != (pinned == 'x') {
                wrong.push(format!("{name:?} ~ {pattern:?}: {matched}"));
            }
        }
    }
    assert!(
        wrong.is_empty(),
        "not as pinned ({answers:?}):\n{}",
        wrong.join("\n")
    );
}
